#!/usr/bin/env python3
"""Generate every app icon: Android, iOS, the web's icons and the favicons.

The builds shipped Flutter's default blue logo, which is the first thing
anyone sees when they install the app or open a tab. This draws the brand mark
instead: the map pin from the brand guidelines, an ink pin on turmeric (v0.2;
it was white on burgundy before 0.24). Until 0.24 it drew only the web's
icons, so the Android launcher, on the platform this app is for, still showed
Flutter's logo.

Every file carries its provenance in a PNG text chunk (`impeccable:prompt`),
the key Impeccable's `embed-prompt --scan` reads: it says the file was drawn
here, not generated by a model or taken from stock.

The pin is drawn analytically rather than traced from the Dart painter — one
circle for the head and the two tangent lines down to the point, which is the
same construction `job_marker.dart` uses and the reason the silhouette matches.

**The pin has a hole since 0.36.** The mark beside "Trust Hire" in the app is
Material's rounded location pin, a head with a round hole in it, on a rounded
turmeric tile. These icons drew a solid teardrop, and the favicon a solid one
on a square-cornered tile: at 16px in a browser tab it read as an ink blob,
not as the app's logo. The hole is what makes a pin a pin at that size.

The favicon also comes as an SVG (`web/favicon.svg`), so a high-density tab
draws it sharp instead of scaling a 32px bitmap; the PNG stays for browsers
that do not take SVG favicons, Safari among them.

Standard library only, and RGBA rather than the RGB writer in
`generate_placeholder_assets.py`, because an icon with square corners on a
light background looks broken on iOS and on a browser tab.

Usage:
    python3 tool/generate_app_icons.py
"""

from __future__ import annotations

import math
import pathlib
import struct
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB_DIR = ROOT / "web"
ICON_DIR = WEB_DIR / "icons"
ANDROID_RES = ROOT / "android" / "app" / "src" / "main" / "res"
IOS_ICONS = ROOT / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"

# Android's legacy launcher icon, per density. The launcher draws it as given,
# so it keeps the rounded square.
ANDROID_SIZES = {
    "mdpi": 48,
    "hdpi": 72,
    "xhdpi": 96,
    "xxhdpi": 144,
    "xxxhdpi": 192,
}

# Brand palette v0.2 (0.24): a turmeric square with an ink pin, the same mark
# that heads the navigation rail.
TURMERIC = (0xF2, 0xA9, 0x00)
INK = (0x16, 0x20, 0x2A)

# The hole in the pin's head, as a share of the head's radius: Material's
# location_on_rounded, the mark in the app, has a 2.5 hole in a 7 head.
HOLE = 0.36

# Samples per axis. 4 is enough to keep the pin's curve clean at 192px and
# costs nothing at these sizes.
SUPERSAMPLE = 4


ORIGIN = (
    "Drawn by code/frontend/tool/generate_app_icons.py: the Trust Hire map "
    "pin in ink (#16202A) on turmeric (#F2A900). Not generated by a model; "
    "not stock."
)


def write_png(
    path: pathlib.Path,
    size: int,
    pixels: list[bytearray],
    *,
    opaque: bool = False,
) -> None:
    """Write 8-bit RGBA rows as a PNG. Minimal encoder, filter type 0.

    `opaque` drops the alpha channel, for iOS, which rejects an app icon that
    has one even when every pixel is solid.
    """
    raw = bytearray()
    for row in pixels:
        raw.append(0)  # filter: none
        if opaque:
            raw.extend(b for i, b in enumerate(row) if i % 4 != 3)
        else:
            raw.extend(row)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    colour_type = 2 if opaque else 6
    header = struct.pack(">IIBBBBB", size, size, 8, colour_type, 0, 0, 0)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"tEXt", b"impeccable:prompt\x00" + ORIGIN.encode("latin-1"))
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


def in_rounded_square(x: float, y: float, size: float, radius: float) -> bool:
    """Whether a point is inside a square with rounded corners."""
    cx = min(max(x, radius), size - radius)
    cy = min(max(y, radius), size - radius)
    return (x - cx) ** 2 + (y - cy) ** 2 <= radius**2


def tangent_points(cx: float, cy: float, r: float, tip: float):
    """Where the pin's straight edges meet its round head.

    The apex, the centre and a tangent point form a right angle at the tangent
    point, so the angle at the centre is arccos(r / d). Deriving the join this
    way is what stops the point looking bolted on: the straight edge leaves the
    curve along it rather than crossing it.

    Returns the half-width at the join and the height it sits at.
    """
    ratio = r / (tip - cy)
    return r * math.sqrt(1 - ratio**2), cy + r * ratio


def in_pin(
    x: float,
    y: float,
    cx: float,
    cy: float,
    r: float,
    tip: float,
    tangents: tuple[float, float],
) -> bool:
    """Whether a point is inside a map pin: a circle union a tangent triangle.

    A triangle, not the cone from the apex. The cone carries on past the
    tangent points and flares out either side of the head, which turns the pin
    into a funnel.
    """
    head = (x - cx) ** 2 + (y - cy) ** 2
    if head <= (r * HOLE) ** 2:
        return False
    if head <= r**2:
        return True

    half_width, join_y = tangents
    if y < join_y or y > tip:
        return False

    # Full width where the edges leave the head, nothing at the point.
    return abs(x - cx) <= half_width * (1 - (y - join_y) / (tip - join_y))


def build_icon(size: int, *, full_bleed: bool, pin_scale: float) -> list[bytearray]:
    """One icon: turmeric ground, ink pin.

    `full_bleed` squares the corners for the maskable variants, where the
    launcher applies its own shape and a rounded source would be clipped twice.
    `pin_scale` shrinks the mark for those same variants, so it survives the
    aggressive circular masks some launchers use.
    """
    radius = 0 if full_bleed else size * 0.22

    # The same proportions as the marker on the map (job_marker.dart): a head
    # of 0.39 of the pin's height, with the point reaching the bottom edge. A
    # longer point reads as a funnel rather than a pin.
    pin_height = size * pin_scale
    head_radius = pin_height * 0.39
    top = (size - pin_height) / 2
    centre_x = size / 2
    head_y = top + head_radius
    tip_y = top + pin_height
    tangents = tangent_points(centre_x, head_y, head_radius, tip_y)

    step = 1.0 / SUPERSAMPLE
    offset = step / 2
    total = SUPERSAMPLE * SUPERSAMPLE

    rows = []
    for py in range(size):
        row = bytearray()
        for px in range(size):
            ground = 0
            mark = 0
            for sy in range(SUPERSAMPLE):
                y = py + offset + sy * step
                for sx in range(SUPERSAMPLE):
                    x = px + offset + sx * step
                    if full_bleed or in_rounded_square(x, y, size, radius):
                        ground += 1
                        if in_pin(
                            x, y, centre_x, head_y, head_radius, tip_y, tangents
                        ):
                            mark += 1

            alpha = round(255 * ground / total)
            if alpha == 0:
                row.extend((0, 0, 0, 0))
                continue

            # Coverage of the mark within the ground that is actually painted.
            t = mark / ground
            colour = tuple(
                round(TURMERIC[i] + (INK[i] - TURMERIC[i]) * t)
                for i in range(3)
            )
            row.extend((*colour, alpha))
        rows.append(row)

    return rows


def build_svg(*, pin_scale: float) -> str:
    """The favicon as an SVG: the same tile, pin and hole, in a 64-unit box."""
    size = 64.0
    radius = size * 0.22
    pin_height = size * pin_scale
    head_radius = pin_height * 0.39
    top = (size - pin_height) / 2
    cx = size / 2
    head_y = top + head_radius
    tip_y = top + pin_height
    half_width, join_y = tangent_points(cx, head_y, head_radius, tip_y)

    def n(value: float) -> str:
        return f"{value:.2f}".rstrip("0").rstrip(".")

    turmeric = "#%02X%02X%02X" % TURMERIC
    ink = "#%02X%02X%02X" % INK
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">\n'
        f"  <!-- {ORIGIN} -->\n"
        f'  <rect width="64" height="64" rx="{n(radius)}" fill="{turmeric}"/>\n'
        f'  <path fill="{ink}" fill-rule="evenodd" d="'
        # Head, the point, then the hole: even-odd leaves the hole unpainted.
        f"M{n(cx - half_width)} {n(join_y)}"
        f"A{n(head_radius)} {n(head_radius)} 0 1 1 {n(cx + half_width)} {n(join_y)}"
        f"L{n(cx)} {n(tip_y)}Z"
        f"M{n(cx + head_radius * HOLE)} {n(head_y)}"
        f"A{n(head_radius * HOLE)} {n(head_radius * HOLE)} 0 1 0 "
        f"{n(cx - head_radius * HOLE)} {n(head_y)}"
        f"A{n(head_radius * HOLE)} {n(head_radius * HOLE)} 0 1 0 "
        f"{n(cx + head_radius * HOLE)} {n(head_y)}Z"
        '"/>\n'
        "</svg>\n"
    )


def main() -> None:
    ICON_DIR.mkdir(parents=True, exist_ok=True)

    targets = [
        (ICON_DIR / "Icon-192.png", 192, False, 0.58),
        (ICON_DIR / "Icon-512.png", 512, False, 0.58),
        # Maskable icons are cropped by the launcher, so the mark stays inside
        # the 80% safe zone the spec guarantees.
        (ICON_DIR / "Icon-maskable-192.png", 192, True, 0.44),
        (ICON_DIR / "Icon-maskable-512.png", 512, True, 0.44),
        # Rounded like the tile beside the name in the app; at 16px the corner
        # is still three pixels, and a square tile read as a different mark.
        # 64px, for a 32px tab at twice the density; browsers that take the
        # SVG never fetch it.
        (WEB_DIR / "favicon.png", 64, False, 0.66),
    ]

    for density, size in ANDROID_SIZES.items():
        targets.append(
            (ANDROID_RES / f"mipmap-{density}" / "ic_launcher.png", size, False, 0.58)
        )

    # iOS masks the icon itself, so it is drawn square and opaque, at every
    # size the asset catalogue names: "Icon-App-20x20@3x.png" is 60px.
    ios = []
    for path in sorted(IOS_ICONS.glob("Icon-App-*.png")):
        points, scale = path.stem.removeprefix("Icon-App-").split("@")
        size = round(float(points.split("x")[0]) * int(scale.rstrip("x")))
        ios.append((path, size))

    for path, size, full_bleed, pin_scale in targets:
        write_png(path, size, build_icon(size, full_bleed=full_bleed, pin_scale=pin_scale))
        print(f"wrote {path.relative_to(ROOT)} ({size}x{size})")

    svg = WEB_DIR / "favicon.svg"
    svg.write_text(build_svg(pin_scale=0.66))
    print(f"wrote {svg.relative_to(ROOT)}")

    for path, size in ios:
        write_png(
            path,
            size,
            build_icon(size, full_bleed=True, pin_scale=0.58),
            opaque=True,
        )
        print(f"wrote {path.relative_to(ROOT)} ({size}x{size}, opaque)")


if __name__ == "__main__":
    main()
